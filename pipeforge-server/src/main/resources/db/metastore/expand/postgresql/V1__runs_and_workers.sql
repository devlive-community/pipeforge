-- Expand migration 1: the runs of jobs and the workers of the cluster. Times are UTC.
-- Applied scripts are never changed; see operations/metastore.

CREATE TABLE job_run (
    id             VARCHAR(64)  NOT NULL,
    job_name       VARCHAR(255) NOT NULL,
    job_yaml       TEXT         NOT NULL,
    status         VARCHAR(16)  NOT NULL,
    submitted_by   VARCHAR(255),
    submitted_at   TIMESTAMP(3)  NOT NULL,
    started_at     TIMESTAMP(3),
    ended_at       TIMESTAMP(3),
    updated_at     TIMESTAMP(3)  NOT NULL,
    error_code     VARCHAR(32),
    error_message  TEXT,
    PRIMARY KEY (id)
);

CREATE INDEX job_run_submitted ON job_run (submitted_at);
CREATE INDEX job_run_job ON job_run (job_name, submitted_at);
CREATE INDEX job_run_status ON job_run (status);

CREATE TABLE job_run_attempt (
    run_id         VARCHAR(64)  NOT NULL,
    attempt        INT          NOT NULL,
    master         VARCHAR(255),
    status         VARCHAR(16)  NOT NULL,
    started_at     TIMESTAMP(3)  NOT NULL,
    ended_at       TIMESTAMP(3),
    error_code     VARCHAR(32),
    error_message  TEXT,
    PRIMARY KEY (run_id, attempt)
);

CREATE TABLE job_run_transition (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    run_id         VARCHAR(64)  NOT NULL,
    attempt        INT          NOT NULL,
    from_status    VARCHAR(16),
    to_status      VARCHAR(16)  NOT NULL,
    occurred_at    TIMESTAMP(3)  NOT NULL,
    reason         TEXT,
    PRIMARY KEY (id)
);

CREATE INDEX job_run_transition_run ON job_run_transition (run_id, id);

CREATE TABLE job_run_metrics (
    run_id         VARCHAR(64)  NOT NULL,
    sampled_at     TIMESTAMP(3)  NOT NULL,
    elapsed_ms     BIGINT       NOT NULL,
    rows_read      BIGINT       NOT NULL,
    rows_written   BIGINT       NOT NULL,
    rows_dirty     BIGINT       NOT NULL,
    rows_failed    BIGINT       NOT NULL,
    metrics_json   TEXT         NOT NULL,
    PRIMARY KEY (run_id, sampled_at)
);

CREATE TABLE worker (
    id             VARCHAR(128) NOT NULL,
    address        VARCHAR(255) NOT NULL,
    slots          INT          NOT NULL,
    labels_json    TEXT,
    version        VARCHAR(64),
    state          VARCHAR(16)  NOT NULL,
    registered_at  TIMESTAMP(3)  NOT NULL,
    heartbeat_at   TIMESTAMP(3)  NOT NULL,
    PRIMARY KEY (id)
);
